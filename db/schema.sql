BEGIN;

CREATE TABLE IF NOT EXISTS compiled_records (
  name_with_valid_delimiters   TEXT        PRIMARY KEY,

  associated_record_identifier TEXT        UNIQUE,

  first_word                   TEXT        NOT NULL
                                 GENERATED ALWAYS AS (
                                   split_part(
                                     trim(regexp_replace(
                                       regexp_replace(lower(
                                         substring(name_with_valid_delimiters
                                                   from '\$a([^$]*)')
                                       ),
                                       '([a-z])\.', '\1', 'g'),
                                       '[^a-z0-9]+', ' ', 'g'
                                     )),
                                     ' ', 1
                                   )
                                 ) STORED,

  first_letter                 VARCHAR(1)  NOT NULL
                                 GENERATED ALWAYS AS (
                                   substring(
                                     trim(regexp_replace(
                                       regexp_replace(lower(
                                         substring(name_with_valid_delimiters
                                                   from '\$a([^$]*)')
                                       ),
                                       '([a-z])\.', '\1', 'g'),
                                       '[^a-z0-9]+', ' ', 'g'
                                     ))
                                     from 1 for 1
                                   )
                                 ) STORED,
  
  canonical_name               TEXT        NOT NULL,

  tag                          VARCHAR(10) NOT NULL,

  comments                     TEXT,


  date                         DATE        
);

CREATE INDEX compiled_records_first_word_idx
  ON compiled_records (first_word);

CREATE INDEX compiled_records_sort_idx
  ON compiled_records (first_letter, first_word, name_with_valid_delimiters);


CREATE TABLE associated_compiled (
  id                   UUID        PRIMARY KEY DEFAULT gen_random_uuid(),

  associated_record_id TEXT        REFERENCES compiled_records(associated_record_identifier)
                                    ON DELETE CASCADE ,

  associated_number    INT         NOT NULL CHECK (associated_number BETWEEN 1 AND 4),

  percent_match        NUMERIC(5,2),

  lcn                  TEXT,

  tag                  VARCHAR(10) NOT NULL,

  comments             TEXT,

  date                 DATE,


  author_name_match    TEXT,

  CONSTRAINT associated_compiled_parent_number_uniq
    UNIQUE (associated_record_id, associated_number)
);


CREATE TABLE new_entries (
  record_identifier  TEXT        PRIMARY KEY,

  tag                            VARCHAR(10)  NOT NULL,

  comments                       TEXT,


  date                           DATE,


  parent_record_name TEXT
);


CREATE TABLE associated_new_entry (
  id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),

  associated_new_entry TEXT       REFERENCES new_entries(record_identifier)
                                    ON DELETE CASCADE,

  associated_number   INT         NOT NULL CHECK (associated_number BETWEEN 1 AND 4),

  percent_match       NUMERIC(5,2),

  lcn                 TEXT,

  tag                 VARCHAR(10) NOT NULL,

  comments            TEXT,


  date                DATE,


  author_name         TEXT,

  CONSTRAINT associated_new_entry_parent_number_uniq
    UNIQUE (associated_new_entry, associated_number)
);
CREATE OR REPLACE FUNCTION set_associated_number()
RETURNS TRIGGER AS $$
DECLARE
  next_num INT;
BEGIN
  IF TG_TABLE_NAME = 'associated_compiled' THEN
    SELECT coalesce(max(associated_number), 0) + 1
      INTO next_num
      FROM associated_compiled
     WHERE associated_record_id = NEW.associated_record_id;
  ELSE
    SELECT coalesce(max(associated_number), 0) + 1
      INTO next_num
      FROM associated_new_entry
     WHERE associated_new_entry = NEW.associated_new_entry;
  END IF;

  IF next_num > 4 THEN
    RAISE EXCEPTION 'at most 4 associated records allowed per parent (table %)', TG_TABLE_NAME;
  END IF;

  NEW.associated_number := next_num;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER associated_compiled_set_number
  BEFORE INSERT ON associated_compiled
  FOR EACH ROW EXECUTE FUNCTION set_associated_number();

CREATE TRIGGER associated_new_entry_set_number
  BEFORE INSERT ON associated_new_entry
  FOR EACH ROW EXECUTE FUNCTION set_associated_number();

CREATE TABLE IF NOT EXISTS audit_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  actor_id    BIGINT,
  action      TEXT NOT NULL CHECK (action IN ('ADD', 'MODIFY', 'DELETE', 'ERROR')),
  table_name  TEXT NOT NULL,
  record_key  TEXT NOT NULL,
  old_data    JSONB,
  new_data    JSONB
);

CREATE INDEX IF NOT EXISTS audit_events_occurred_at_idx
  ON audit_events (occurred_at, id);

CREATE OR REPLACE FUNCTION audit_catalog_change()
RETURNS TRIGGER AS $$
DECLARE
  actor BIGINT;
  old_row JSONB;
  new_row JSONB;
  row_key TEXT;
  event_action TEXT;
BEGIN
  actor := NULLIF(current_setting('app.user_id', true), '')::BIGINT;

  IF TG_OP = 'INSERT' THEN
    new_row := to_jsonb(NEW);
    row_key := new_row ->> TG_ARGV[0];
    event_action := 'ADD';
  ELSIF TG_OP = 'UPDATE' THEN
    old_row := to_jsonb(OLD);
    new_row := to_jsonb(NEW);
    row_key := new_row ->> TG_ARGV[0];
    event_action := 'MODIFY';
  ELSE
    old_row := to_jsonb(OLD);
    row_key := old_row ->> TG_ARGV[0];
    event_action := 'DELETE';
  END IF;

  INSERT INTO audit_events (
    actor_id, action, table_name, record_key, old_data, new_data
  ) VALUES (
    actor, event_action, TG_TABLE_NAME, row_key, old_row, new_row
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS audit_compiled_records ON compiled_records;
CREATE TRIGGER audit_compiled_records
  AFTER INSERT OR UPDATE OR DELETE ON compiled_records
  FOR EACH ROW EXECUTE FUNCTION audit_catalog_change('name_with_valid_delimiters');

DROP TRIGGER IF EXISTS audit_associated_compiled ON associated_compiled;
CREATE TRIGGER audit_associated_compiled
  AFTER INSERT OR UPDATE OR DELETE ON associated_compiled
  FOR EACH ROW EXECUTE FUNCTION audit_catalog_change('id');

DROP TRIGGER IF EXISTS audit_new_entries ON new_entries;
CREATE TRIGGER audit_new_entries
  AFTER INSERT OR UPDATE OR DELETE ON new_entries
  FOR EACH ROW EXECUTE FUNCTION audit_catalog_change('record_identifier');

DROP TRIGGER IF EXISTS audit_associated_new_entry ON associated_new_entry;
CREATE TRIGGER audit_associated_new_entry
  AFTER INSERT OR UPDATE OR DELETE ON associated_new_entry
  FOR EACH ROW EXECUTE FUNCTION audit_catalog_change('id');

COMMIT;